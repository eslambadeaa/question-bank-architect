# Let's find 4 patterns for MCQ (15) and TF (10):
# Each lesson must have 25 questions.
# Over 4 lessons (100 Q: 60 MCQ, 40 TF):
# Total سهل = 30 (18 MCQ, 12 TF -> 30% each)
# Total متوسط = 30 (18 MCQ, 12 TF -> 30% each)
# Total صعب = 15 (9 MCQ, 6 TF -> 15% each)
# Total صعب جدا = 15 (9 MCQ, 6 TF -> 15% each)
# Total تفوق = 10 (6 MCQ, 4 TF -> 10% each)

# Look at the beauty of this:
# 60 MCQ:
# 18 سهل (30%), 18 متوسط (30%), 9 صعب (15%), 9 صعب جدا (15%), 6 تفوق (10%) = 60!
# 40 TF:
# 12 سهل (30%), 12 متوسط (30%), 6 صعب (15%), 6 صعب جدا (15%), 4 تفوق (10%) = 40!

# Now let's distribute 60 MCQ across 4 lessons (15 each):
# L1: 4 سهل, 5 متوسط, 2 صعب, 2 صعب جدا, 2 تفوق (15)
# L2: 5 سهل, 4 متوسط, 2 صعب, 3 صعب جدا, 1 تفوق (15)
# L3: 5 سهل, 4 متوسط, 3 صعب, 2 صعب جدا, 1 تفوق (15)
# L4: 4 سهل, 5 متوسط, 2 صعب, 2 صعب جدا, 2 تفوق (15)
# Sum MCQ: 4+5+5+4 = 18 سهل, 5+4+4+5 = 18 متوسط, 2+2+3+2 = 9 صعب, 2+3+2+2 = 9 صعب جدا, 2+1+1+2 = 6 تفوق! EXACT!

# Now distribute 40 TF across 4 lessons (10 each):
# L1: 3 سهل, 3 متوسط, 2 صعب, 1 صعب جدا, 1 تفوق (10)
# L2: 3 سهل, 3 متوسط, 1 صعب, 2 صعب جدا, 1 تفوق (10)
# L3: 3 سهل, 3 متوسط, 1 صعب, 2 صعب جدا, 1 تفوق (10)
# L4: 3 سهل, 3 متوسط, 2 صعب, 1 صعب جدا, 1 تفوق (10)
# Sum TF: 3*4 = 12 سهل, 3*4 = 12 متوسط, 2+1+1+2 = 6 صعب, 1+2+2+1 = 6 صعب جدا, 1*4 = 4 تفوق! EXACT!

